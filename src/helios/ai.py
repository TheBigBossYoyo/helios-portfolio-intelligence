"""Milestone 6 — Claude analysis of the M3 analytics.

## What this is, and what it deliberately is not

Helios asks Claude to **describe** a portfolio it can already measure. Every fact the model is
given comes from the M3 replay and the M5 news store; the model adds structure and prose, not
data. Concretely:

* **No forecasts, no buy/sell/hold.** The output schema has no price target, no rating, and no
  action field, so there is nowhere for one to go. The system prompt says so too, but the schema
  is the enforcement.
* **Every observation must cite its evidence.** `evidence` is a required schema field and must
  quote a figure from the supplied analytics. An observation that cannot cite one is invalid
  output, not a softly-worded guess.
* **Statuses travel with the numbers.** Metrics M3 declared `insufficient_data` or `unavailable`
  are passed through with that status attached, so the model sees what is unknown rather than
  inferring a value from an absent one.
* **Raw-first.** The exact request and response are stored in `ai_runs` before anything is
  parsed, so any published insight can be traced back to the numbers behind it.

This is descriptive analysis for personal use. It is not investment advice, and the disclosure
travels with the output through the API, the CLI and the dashboard.
"""

