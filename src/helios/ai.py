def _metric(value: MetricValue) -> dict[str, Any]:
    """Serialise a metric with its status, so 'unknown' stays visibly unknown."""
    if value.status != "ok" or value.value is None:
        return {"status": value.status, "value": None, "note": value.detail}
    return {"status": "ok", "value": round(value.value, 6), "observations": value.observations}


def build_payload(
    report: PerformanceReport, news: list[NewsItem], *, max_news: int
) -> dict[str, Any]:
    """Flatten the analytics and headlines into the exact JSON the model receives."""
    return {
        "window": {"start": str(report.start_date), "end": str(report.end_date)},
        "conventions": {
            "flow_timing": report.flow_timing,
            "annualization_days": report.annualization_days,
            "base_currency": "EUR",
        },
        "returns": {
            "cumulative_twr": _metric(report.cumulative_twr),
            "annualized": _metric(report.annualized_return),
            "xirr": _metric(report.xirr),
        },
        "risk": {
            "volatility": _metric(report.volatility),
            "downside_volatility": _metric(report.downside_volatility),
            "sharpe": _metric(report.sharpe),
            "sortino": _metric(report.sortino),
            "calmar": _metric(report.calmar),
            "max_drawdown": _metric(report.max_drawdown),
            "time_underwater_days": _metric(report.time_underwater_days),
            "recovery_days": _metric(report.recovery_days),
            "var_95_1d": _metric(report.var_95_1d),
            "cvar_95_1d": _metric(report.cvar_95_1d),
            "var_99_10d": _metric(report.var_99_10d),
            "cvar_99_10d": _metric(report.cvar_99_10d),
        },
        "concentration": {
            "hhi": _metric(report.hhi),
            "effective_positions": _metric(report.effective_number_of_positions),
            "top5_weight": _metric(report.top5_weight),
        },
        "contributions": [
            {
                "ticker": item.key,
                "weight": round(item.weight, 6),
                "status": item.status,
                "return": None if item.return_value is None else round(item.return_value, 6),
                "contribution": None if item.contribution is None else round(item.contribution, 6),
            }
            for item in report.contributions
        ],
        "benchmarks": [
            {
                "label": item.benchmark.label,
                "symbol": item.benchmark.providerSymbol
                if hasattr(item.benchmark, "providerSymbol")
                else item.benchmark.provider_symbol,
                "beta": _metric(item.beta),
                "correlation": _metric(item.correlation),
                "tracking_error": _metric(item.tracking_error),
            }
            for item in report.beta_vs_benchmarks
        ],
        "correlation_clusters": {
            "status": report.correlation_clusters.status,
            "cluster_count": report.correlation_clusters.cluster_count,
            "detail": report.correlation_clusters.detail,
            "assignments": [
                {"ticker": a.key, "cluster": a.cluster, "weight": round(a.weight, 6)}
                for a in report.correlation_clusters.assignments
            ],
        },
        "attribution": {
            "status": report.attribution.status,
            "detail": report.attribution.detail,
        },
        "factor_exposure": {
            "status": report.ff5_momentum_regression.status,
            "detail": report.ff5_momentum_regression.detail,
            "r_squared": report.ff5_momentum_regression.r_squared,
            "coefficients": report.ff5_momentum_regression.coefficients,
        },
        "passive_counterfactual": {
            "status": report.passive_counterfactual.status,
            "benchmark": report.passive_counterfactual.benchmark_label,
            "invested_eur": _decimal(report.passive_counterfactual.invested_eur),
            "passive_value_eur": _decimal(report.passive_counterfactual.final_value_eur),
            "actual_nav_eur": _decimal(report.passive_counterfactual.actual_nav_eur),
            "detail": report.passive_counterfactual.detail,
        },
        "method_notes": report.notes,
        "recent_news": [
            {
                "ticker": item.t212_ticker,
                "source": item.source_label,
                "headline": item.headline,
                "published_at": item.published_at.isoformat() if item.published_at else None,
            }
            for item in news[:max_news]
        ],
    }


def _decimal(value: object) -> str | None:
    return None if value is None else str(value)


