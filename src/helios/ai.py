PROVIDER = "anthropic"
DISCLOSURE = (
    "Descriptive analysis of your own portfolio data, generated by an AI model. "
    "It is not investment advice, not a recommendation to buy or sell, and not a forecast. "
    "Every statement is derived from figures Helios reconstructed from your Trading 212 history."
)

SEVERITIES = ("info", "notable", "elevated")
CATEGORIES = (
    "concentration",
    "risk",
    "performance",
    "attribution",
    "data_quality",
    "news",
)

SYSTEM_PROMPT = """\
You are a portfolio analyst writing a factual briefing for the owner of the portfolio.

You will be given a JSON document of metrics Helios computed from the owner's own brokerage
history, plus recent headlines from sources the owner configured. Your job is to describe what
those numbers show.

Hard rules:
- Use ONLY the supplied figures. Never introduce a number, price, ratio or fact that is not in
  the input. If you want to say something you cannot support from the input, omit it.
- Every observation must quote the specific figure it rests on, in the `evidence` field. If you
  cannot quote a figure, do not make the observation.
- Metrics carry a `status`. When the status is not "ok", the metric is UNKNOWN — say it is
  unavailable, never infer or estimate a value for it.
- Do NOT give investment advice. No buy/sell/hold, no price targets, no forecasts, no
  suggestions to rebalance, and no opinions on whether a holding is a good investment.
- Describe risk factually ("the top holding is 62% of NAV") rather than judgementally ("this is
  dangerously concentrated").
- Headlines are supplied for context only. You may note that coverage exists for a holding; you
  may not infer a price impact from a headline.

Rank observations by how much they would change the owner's understanding of their portfolio,
most significant first."""

OUTPUT_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "summary": {
            "type": "string",
            "description": "Two or three sentences describing the portfolio's current shape.",
        },
        "observations": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "category": {"type": "string", "enum": list(CATEGORIES)},
                    "t212_ticker": {
                        "type": ["string", "null"],
                        "description": "Holding this concerns, or null if portfolio-wide.",
                    },
                    "headline": {"type": "string"},
                    "detail": {"type": "string"},
                    "evidence": {
                        "type": "string",
                        "description": "The specific figure from the input this rests on.",
                    },
                    "severity": {"type": "string", "enum": list(SEVERITIES)},
                },
                "required": [
                    "category",
                    "t212_ticker",
                    "headline",
                    "detail",
                    "evidence",
                    "severity",
                ],
                "additionalProperties": False,
            },
        },
        "unavailable_metrics": {
            "type": "array",
            "items": {"type": "string"},
            "description": "Metrics the input reported as unavailable or insufficient.",
        },
    },
    "required": ["summary", "observations", "unavailable_metrics"],
    "additionalProperties": False,
}


class AiUnavailableError(RuntimeError):
    """Raised when analysis cannot run at all — no key, or no analytics to describe."""


@dataclass(frozen=True)
class AiObservationView:
    rank: int
    category: str
    t212_ticker: str | None
    headline: str
    detail: str
    evidence: str
    severity: str


@dataclass(frozen=True)
class AiAnalysis:
    status: str
    as_of: datetime
    model: str
    served_by_model: str | None
    effort: str | None
    summary: str | None
    observations: list[AiObservationView]
    unavailable_metrics: list[str]
    input_tokens: int | None
    output_tokens: int | None
    cache_read_tokens: int | None
    disclosure: str
    detail: str | None = None


@dataclass(frozen=True)
class AiBrief:
    """What the model is told and the shape its answer must take."""

    system: str
    schema: dict[str, Any]
    instruction: str


ANALYSIS_BRIEF = AiBrief(
    system=SYSTEM_PROMPT,
    schema=OUTPUT_SCHEMA,
    instruction="Analyse this portfolio. Respond only with the JSON schema.",
)


class AiClient(Protocol):
    async def analyse(
        self, payload: dict[str, Any], *, brief: AiBrief | None = None
    ) -> AiClientResult: ...


@dataclass(frozen=True)
class AiClientResult:
    status: str
    model: str
    served_by_model: str | None
    parsed: dict[str, Any] | None
    raw_response: dict[str, Any]
    input_tokens: int | None
    output_tokens: int | None
    cache_read_tokens: int | None
    detail: str | None = None


class NullAiClient:
    """Used when no API key is configured; keeps the whole pipeline runnable offline."""

    async def analyse(
        self, payload: dict[str, Any], *, brief: AiBrief | None = None
    ) -> AiClientResult:
        del payload, brief
        return AiClientResult(
            status="unavailable",
            model="none",
            served_by_model=None,
            parsed=None,
            raw_response={},
            input_tokens=None,
            output_tokens=None,
            cache_read_tokens=None,
            detail=(
                "No Anthropic API key configured. Set HELIOS_ANTHROPIC_API_KEY to enable "
                "AI analysis."
            ),
        )


class ClaudeAiClient:
    """Calls the Messages API with structured outputs and adaptive thinking."""

    def __init__(self, settings: Settings) -> None:
        self._settings = settings
        key = settings.anthropic_api_key
        self._client = (
            AsyncAnthropic(
                api_key=key.get_secret_value(), timeout=settings.anthropic_timeout_seconds
            )
            if key is not None
            else None
        )

    async def aclose(self) -> None:
        if self._client is not None:
            await self._client.close()

    async def analyse(
        self, payload: dict[str, Any], *, brief: AiBrief | None = None
    ) -> AiClientResult:
        if self._client is None:
            return await NullAiClient().analyse(payload)
        settings = self._settings
        brief = brief or ANALYSIS_BRIEF
        try:
            response = await self._client.beta.messages.create(
                model=settings.anthropic_model,
                max_tokens=settings.anthropic_max_tokens,
                # Adaptive thinking: Claude decides how much reasoning each portfolio needs.
                thinking={"type": "adaptive"},
                output_config={
                    "effort": settings.anthropic_effort,
                    "format": {"type": "json_schema", "schema": brief.schema},
                },
                # The system prompt is byte-stable across runs, so it caches; the portfolio
                # payload that follows is what varies.
                system=[
                    {
                        "type": "text",
                        "text": brief.system,
                        "cache_control": {"type": "ephemeral"},
                    }
                ],
                # Opus 5's classifiers can decline a request; this re-runs it server-side
                # rather than surfacing a refusal.
                betas=["server-side-fallback-2026-06-01"],
                fallbacks=[{"model": settings.anthropic_fallback_model}],
                messages=[
                    {
                        "role": "user",
                        "content": (
                            brief.instruction
                            + "\n\n"
                            + json.dumps(payload, indent=2, sort_keys=True)
                        ),
                    }
                ],
            )
        except RateLimitError as error:
            return _client_error("rate_limited", error)
        except APIStatusError as error:
            return _client_error("api_error", error)
        except APIConnectionError as error:
            return _client_error("unreachable", error)

        raw = response.model_dump(mode="json")
        served_by = _served_by(response)
        usage = getattr(response, "usage", None)
        if response.stop_reason == "refusal":
            return AiClientResult(
                status="refused",
                model=settings.anthropic_model,
                served_by_model=served_by,
                parsed=None,
                raw_response=raw,
                input_tokens=getattr(usage, "input_tokens", None),
                output_tokens=getattr(usage, "output_tokens", None),
                cache_read_tokens=getattr(usage, "cache_read_input_tokens", None),
                detail="The model declined this request and the fallback did not answer either.",
            )
        # `content` is a union of block types; only text blocks carry the structured payload.
        text = "".join(block.text for block in response.content if isinstance(block, BetaTextBlock))
        try:
            parsed = json.loads(text)
        except ValueError:
            return AiClientResult(
                status="unparseable",
                model=settings.anthropic_model,
                served_by_model=served_by,
                parsed=None,
                raw_response=raw,
                input_tokens=getattr(usage, "input_tokens", None),
                output_tokens=getattr(usage, "output_tokens", None),
                cache_read_tokens=getattr(usage, "cache_read_input_tokens", None),
                detail="The model's response was not valid JSON.",
            )
        return AiClientResult(
            status="ok",
            model=settings.anthropic_model,
            served_by_model=served_by,
            parsed=parsed if isinstance(parsed, dict) else None,
            raw_response=raw,
            input_tokens=getattr(usage, "input_tokens", None),
            output_tokens=getattr(usage, "output_tokens", None),
            cache_read_tokens=getattr(usage, "cache_read_input_tokens", None),
        )


def _client_error(status: str, error: Exception) -> AiClientResult:
    # Only the class name travels — an API error body can echo request content.
    return AiClientResult(
        status=status,
        model="unknown",
        served_by_model=None,
        parsed=None,
        raw_response={},
        input_tokens=None,
        output_tokens=None,
        cache_read_tokens=None,
        detail=error.__class__.__name__,
    )


def _served_by(response: Any) -> str | None:
    """Which model actually answered — a fallback may have taken over."""
    usage = getattr(response, "usage", None)
    iterations = getattr(usage, "iterations", None) or []
    for entry in iterations:
        if getattr(entry, "type", None) == "fallback_message":
            return str(getattr(response, "model", "")) or None
    return None


