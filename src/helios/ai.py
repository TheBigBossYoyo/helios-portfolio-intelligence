class AiAnalysisService:
    def __init__(
        self,
        repository: PortfolioRepository,
        settings: Settings,
        performance_service: Any,
        client: AiClient | None = None,
        clock: Clock | None = None,
    ) -> None:
        self._repository = repository
        self._settings = settings
        self._performance = performance_service
        self._client = client or NullAiClient()
        self._clock = clock or SystemClock()

    @property
    def enabled(self) -> bool:
        return self._settings.anthropic_api_key is not None

    async def analyse(self) -> AiAnalysis:
        now = self._clock.utcnow()
        try:
            report = await self._performance.get_report()
        except NoPerformanceDataError as error:
            raise AiUnavailableError(
                "No replayed analytics to describe. Run a performance replay first."
            ) from error
        news = await self._repository.list_news_items(limit=self._settings.ai_max_news_items)
        payload = build_payload(report, news, max_news=self._settings.ai_max_news_items)
        result = await self._client.analyse(payload)

        # Raw-first: the request and response land before anything is parsed out of them.
        run_id = await self._repository.insert_ai_run(
            AiRun(
                ts=now,
                provider=PROVIDER,
                model=result.model,
                effort=self._settings.anthropic_effort,
                status=result.status,
                detail=result.detail,
                prompt_json=payload,
                response_json=result.raw_response or None,
                input_tokens=result.input_tokens,
                output_tokens=result.output_tokens,
                cache_read_tokens=result.cache_read_tokens,
                served_by_model=result.served_by_model,
            )
        )

        if result.status != "ok" or result.parsed is None:
            return AiAnalysis(
                status=result.status,
                as_of=now,
                model=result.model,
                served_by_model=result.served_by_model,
                effort=self._settings.anthropic_effort,
                summary=None,
                observations=[],
                unavailable_metrics=[],
                input_tokens=result.input_tokens,
                output_tokens=result.output_tokens,
                cache_read_tokens=result.cache_read_tokens,
                disclosure=DISCLOSURE,
                detail=result.detail,
            )

        observations = parse_observations(result.parsed)
        await self._repository.insert_ai_observations(
            [
                AiObservation(
                    run_id=run_id,
                    rank=view.rank,
                    category=view.category,
                    t212_ticker=view.t212_ticker,
                    headline=view.headline,
                    detail=view.detail,
                    evidence=view.evidence,
                    severity=view.severity,
                )
                for view in observations
            ]
        )
        summary = result.parsed.get("summary")
        unavailable = result.parsed.get("unavailable_metrics")
        return AiAnalysis(
            status="ok",
            as_of=now,
            model=result.model,
            served_by_model=result.served_by_model,
            effort=self._settings.anthropic_effort,
            summary=summary if isinstance(summary, str) else None,
            observations=observations,
            unavailable_metrics=[m for m in unavailable or [] if isinstance(m, str)],
            input_tokens=result.input_tokens,
            output_tokens=result.output_tokens,
            cache_read_tokens=result.cache_read_tokens,
            disclosure=DISCLOSURE,
        )

    async def latest(self, kind: str = "analysis") -> AiAnalysis | None:
        """The most recent stored run, so the dashboard costs nothing to open."""
        run = await self._repository.latest_ai_run(kind)
        if run is None:
            return None
        observations = await self._repository.list_ai_observations(run.id)
        return AiAnalysis(
            status=run.status,
            as_of=run.ts,
            model=run.model,
            served_by_model=run.served_by_model,
            effort=run.effort,
            summary=_stored_summary(run),
            observations=[
                AiObservationView(
                    rank=row.rank,
                    category=row.category,
                    t212_ticker=row.t212_ticker,
                    headline=row.headline,
                    detail=row.detail,
                    evidence=row.evidence,
                    severity=row.severity,
                )
                for row in observations
            ],
            unavailable_metrics=_stored_unavailable(run),
            input_tokens=run.input_tokens,
            output_tokens=run.output_tokens,
            cache_read_tokens=run.cache_read_tokens,
            disclosure=DISCLOSURE,
            detail=run.detail,
        )


def parse_observations(
    parsed: dict[str, Any], *, categories: Sequence[str] = CATEGORIES
) -> list[AiObservationView]:
    """Keep only well-formed observations that cite evidence.

    An observation without evidence is dropped rather than shown: the citation is the whole
    mechanism by which an unfounded claim is visible, so an uncited one has no standing.
    """
    rows = parsed.get("observations")
    if not isinstance(rows, list):
        return []
    views: list[AiObservationView] = []
    for index, row in enumerate(rows, start=1):
        if not isinstance(row, dict):
            continue
        headline = row.get("headline")
        detail = row.get("detail")
        evidence = row.get("evidence")
        if not isinstance(headline, str) or not isinstance(detail, str):
            continue
        if not isinstance(evidence, str) or not evidence.strip():
            continue
        category = row.get("category")
        severity = row.get("severity")
        ticker = row.get("t212_ticker")
        views.append(
            AiObservationView(
                rank=index,
                category=(
                    category
                    if isinstance(category, str) and category in categories
                    else categories[0]
                ),
                t212_ticker=ticker if isinstance(ticker, str) and ticker else None,
                headline=headline.strip(),
                detail=detail.strip(),
                evidence=evidence.strip(),
                severity=severity if severity in SEVERITIES else "info",
            )
        )
    return views


def _stored_summary(run: AiRun) -> str | None:
    parsed = _stored_parsed(run)
    summary = parsed.get("summary") if parsed else None
    return summary if isinstance(summary, str) else None


def _stored_unavailable(run: AiRun) -> list[str]:
    parsed = _stored_parsed(run)
    values = parsed.get("unavailable_metrics") if parsed else None
    return [item for item in values or [] if isinstance(item, str)]


def _stored_parsed(run: AiRun) -> dict[str, Any] | None:
    response = run.response_json
    if not isinstance(response, dict):
        return None
    blocks = response.get("content")
    if not isinstance(blocks, list):
        return None
    for block in blocks:
        if isinstance(block, dict) and block.get("type") == "text":
            try:
                loaded = json.loads(block.get("text") or "")
            except ValueError:
                return None
            return loaded if isinstance(loaded, dict) else None
    return None
